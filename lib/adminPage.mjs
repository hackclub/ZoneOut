        "function termPattern(terms) {",
        "  if (!terms.length) return null;",
        "  var escaped = terms.map(function (t) { return t.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&'); });",
        "  return new RegExp('(' + escaped.join('|') + ')', 'gi');",
        "}",

        "function paintCell(td, text, pattern) {",
        "  if (!pattern) { td.textContent = text; return; }",
        "  td.textContent = '';",
        "  var last = 0;",
        "  var match;",
        "  pattern.lastIndex = 0;",
        "  while ((match = pattern.exec(text)) !== null) {",
        "    if (!match[0]) { pattern.lastIndex++; continue; }",
        "    if (match.index > last) td.appendChild(document.createTextNode(text.slice(last, match.index)));",
        "    var hit = document.createElement('mark');",
        "    hit.textContent = match[0];",
        "    td.appendChild(hit);",
        "    last = match.index + match[0].length;",
        "  }",
        "  if (last < text.length) td.appendChild(document.createTextNode(text.slice(last)));",
        "}",

        "function filterIndex(index, terms, pattern) {",
        "  var shown = 0;",
        "  index.forEach(function (row) {",
        "    var hit = terms.every(function (term) { return row.text.indexOf(term) !== -1; });",
        "    row.tr.hidden = !hit;",
        "    if (!hit) return;",
        "    shown++;",
        "    row.cells.forEach(function (c) { paintCell(c.td, c.text, pattern); });",
        "  });",
        "  return shown;",
        "}",

        "function applyFilter() {",
