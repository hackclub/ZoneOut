        "  var pattern = termPattern(terms);",
        "  var shownUsers = filterIndex(userIndex, terms, pattern);",
        "  var shownSuggestions = filterIndex(suggestionIndex, terms, pattern);",
        "  var shownProjects = filterIndex(projectIndex, terms, pattern);",
        "  filterIndex(reviewIndex, terms, pattern);",
        "  filterIndex(orderIndex, terms, pattern);",

